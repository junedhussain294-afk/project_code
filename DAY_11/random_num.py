import numpy as np
rand_int = np.random.randint(1, 101)   # Random integer between 1 and 100
rand_float = np.random.rand()          # Random float between 0 and 1
rand_array = np.random.rand(5)         # Random array of size 5

print("Random Integer:", rand_int)
print("Random Float:", rand_float)
print("Random Array:", rand_array)